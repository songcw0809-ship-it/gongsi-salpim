export interface ChecklistRule {
  /** 기준 번호. 지적마다 이 번호를 붙인다. 예: "R10-1" */
  id: string;
  scope: RuleScope;
  category: RuleCategory;
  /** AI에게 물을 점검 질문 */
  question: string;
  /** 고시 원문에서 가져온 기준 문구 */
  criterion: string;
  /** 고시 안의 위치 */
  source: string;
  /** 공통 기준이 적용되는 갱신주기. 없으면 모든 항목에 적용 */
  cycles?: readonly CycleKind[];
}

